"""Public API snapshots of OpenCine (C-API). Standard library only; Swift side needs macOS + Xcode.

  atlas api                 list the snapshot files and their sizes
  atlas api <module>        print one module's public API (Swift product or Gradle module)
  atlas api --check         compare the iOS Simulator build's public API with atlas/api/swift; fail
                            on any difference (CI, after BUILD below)
  atlas api --write         rewrite atlas/api/swift/<Module>.txt from that build
  --build                   run BUILD first

Swift: `swift-api-digester -dump-sdk` reads each library product's module from the iOS Simulator
build of the package (what the apps ship; watchOS- or macOS-only `#if` API is not listed) and
every public declaration becomes one sorted line. The lines do not depend on the Xcode version
(CI runs Xcode 26, contributors may run 27; see `_type` and `_conformances`). Kotlin: the Kotlin
Gradle plugin's ABI validation (Kotlin/JVM modules) and `dumpAndroidApi` (Android library modules, the same
ABI tool) keep Android/<module>/api/<module>.api (`./gradlew checkKotlinAbi checkAndroidApi`, update with
`./gradlew updateKotlinAbi updateAndroidApi`); this command only reads those files.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import atlas
import hub

OK, FAIL, USAGE, INCOMPLETE = atlas.OK, atlas.FAIL, atlas.USAGE, atlas.INCOMPLETE
SWIFT_DIR = Path("atlas/api/swift")
# CI points ATLAS_API_DERIVED at the derived data of its other iOS Simulator builds to reuse them.
DERIVED = Path(os.path.expanduser(os.environ.get("ATLAS_API_DERIVED", ".build/api-ios")))
BUILD = ["xcodebuild", "-scheme", "OpenCine-Package", "-destination", "generic/platform=iOS Simulator",
         "-derivedDataPath", str(DERIVED), "-skipMacroValidation", "-skipPackagePluginValidation", "-quiet", "build"]
UPDATE = "python3 atlas/tools/atlas.py api --write --build and commit atlas/api/swift"
HEADER = ("# Public API of {m} (Swift). Generated by `atlas api --write` from the iOS Simulator build;\n"
          "# API declared only for watchOS or macOS is not listed. Do not edit; one declaration per line.\n")
IMPLICIT_CONFORMANCES = {"Copyable", "Escapable", "BitwiseCopyable", "SendableMetatype"}
TYPE_KEYWORD = {"Struct": "struct", "Enum": "enum", "Class": "class", "Protocol": "protocol", "Actor": "actor"}
# A protocol requirement's implicit `<Self where Self : P>`: noise on every requirement line.
ASYNC = re.compile(r"YaK?F$")
PROTOCOL_SELF = re.compile(r"^<Self where Self : [\w.]+>$")
# A Swift USR names its module: `s:5UIKit23UITraitChangeObservableP`; `s:s...` and `s:S...` are the
# standard library. A Clang USR (`c:objc(pl)UIAppearance`) is an SDK protocol.
STDLIB_USR = re.compile(r"^s:[sS]")
SWIFT_USR_MODULE = re.compile(r"^s:(\d+)")
STDLIB_MODULES = {"Swift", "_Concurrency"}


# ---------------------------------------------------------------- rendering

def _type(node):
    if not node:
        return "?"
    # Toolchain independence: Xcode 26's digester prints a typealias of a non-escaping closure
    # parameter as the function type itself, Xcode 27 keeps the alias. Print the function type.
    children = node.get("children") or []
    if (node.get("kind") == "TypeNameAlias" and "noescape" in node.get("typeAttributes", [])
            and children and children[0].get("kind") == "TypeFunc"):
        return _type(children[0])
    return node.get("printedName", "?")


def _protocol_module(usr):
    """The module that declares a conformance's protocol: "Swift" for the standard library, None for
    a Clang (SDK) protocol."""
    if STDLIB_USR.match(usr):
        return "Swift"
    match = SWIFT_USR_MODULE.match(usr)
    return usr[match.end():match.end() + int(match.group(1))] if match else None


def _conformances(node, package):
    """Sorted conformance names of a type. A class with an SDK superclass (UIView, NSObject) lists that
    superclass first and only its conformances to standard-library and package protocols: the SDK
    protocols it inherits change with the SDK version (iOS 27 adds CLBodyIdentifiable to UIView), so
    listing them would make the snapshot depend on the Xcode that generated it."""
    conf = [c for c in node.get("conformances", []) if c.get("printedName") not in IMPLICIT_CONFORMANCES]
    supers = node.get("superclassNames") or []
    if any(s.split(".", 1)[0] not in package for s in supers):
        keep = package | STDLIB_MODULES
        conf = [c for c in conf if _protocol_module(c.get("usr", "")) in keep]
    return supers[:1] + sorted(c["printedName"] for c in conf)


def _signature(name, children):
    """`name(label: Type, _: Type) -> Ret` from a digester printedName and its type children."""
    ret, params = (children[0] if children else None), children[1:]
    base, _, labels = name.partition("(")
    labels = [label for label in labels.rstrip(")").split(":") if label != ""] if labels else []
    args = ", ".join(f"{labels[i] if i < len(labels) else '_'}: {_type(p)}" for i, p in enumerate(params))
    return f"{base}({args})", _type(ret)


def _render(node, path, out, package):
    kind, decl = node.get("kind"), node.get("declKind")
    if node.get("implicit") or kind == "Import":
        return
    name = node.get("name", "")
    full = ".".join(path + [name]) if name else ".".join(path)
    mods = "static " if node.get("static") else ""
    if kind == "TypeDecl" and node.get("isExternal"):
        # Public members this module adds to another module's type.
        out.append(f"extension {node.get('moduleName')}.{name}")
        for child in node.get("children", []):
            _render(child, path + [name], out, package)
    elif kind == "TypeDecl":
        conf = _conformances(node, package)
        generic = node.get("genericSig", "")
        out.append(f"{TYPE_KEYWORD.get(decl, decl.lower())} {full}{generic}" + (f": {', '.join(conf)}" if conf else ""))
        for child in node.get("children", []):
            _render(child, path + [name], out, package)
    elif decl == "EnumElement":
        # (Enum.Type) -> (Payload) -> Enum when the case has a payload, else (Enum.Type) -> Enum.
        inner = (node.get("children") or [{}])[0].get("children") or [{}]
        payload = inner[0]["printedName"].rsplit(" -> ", 1)[0] if inner[0].get("kind") == "TypeFunc" else ""
        out.append(f"case {full}{payload}")
    elif kind == "Var":
        accessors = {a.get("accessorKind") or a.get("name") for a in node.get("accessors", [])}
        keyword = "let" if node.get("isLet") else "var"
        setter = " { get set }" if "Set" in accessors and keyword == "var" else ""
        out.append(f"{mods}{keyword} {full}: {_type((node.get('children') or [None])[0])}{setter}")
    elif kind in ("Function", "Constructor", "Subscript"):
        sig, ret = _signature(node.get("printedName", name), node.get("children", []))
        keyword = {"Function": "func", "Constructor": "init", "Subscript": "subscript"}[kind]
        generic = PROTOCOL_SELF.sub("", node.get("genericSig", ""))
        # The dump has no async flag; the mangled function type ends in Ya (async) [K (throws)] F.
        throws = (" async" if ASYNC.search(node.get("mangledName", "")) else "") + (" throws" if node.get("throwing") else "")
        owner = ".".join(path)
        label = sig if kind == "Function" else sig.split("(", 1)[1].join(["(", ""])
        target = f"{owner}.{label}" if owner and kind == "Function" else (f"{owner}{label}" if owner else label)
        tail = "" if kind == "Constructor" else f" -> {ret}"
        out.append(f"{mods}{keyword} {target}{generic}{throws}{tail}")
    elif kind == "TypeAlias":
        out.append(f"typealias {full} = {_type((node.get('children') or [None])[0])}")
    elif kind == "AssociatedType":
        out.append(f"associatedtype {full}")
    else:
        out.append(f"{(decl or kind).lower()} {full}")


def render_dump(module, dump, package=frozenset()):
    """Sorted, de-duplicated public declaration lines of one digester dump. `package` names the
    package's modules (the rest is the SDK or the standard library)."""
    out = []
    package = frozenset(package) | {module}
    for child in dump.get("ABIRoot", {}).get("children", []):
        _render(child, [], out, package)
    own = re.compile(rf"\b{re.escape(module)}\.(?=[A-Z_])")  # the module's own names read unqualified
    return HEADER.format(m=module) + "".join(f"{line}\n" for line in sorted({own.sub("", ln) for ln in out}))


# ---------------------------------------------------------------- Swift build

def swift_products(top):
    """Library products of the OpenCine package (each product names one module)."""
    text = (Path(top) / "Package.swift").read_text()
    return sorted(set(re.findall(r'\.library\(\s*name:\s*"([^"]+)"', text)))


def package_modules(top):
    """Every target (module) of the OpenCine package."""
    text = (Path(top) / "Package.swift").read_text()
    return frozenset(re.findall(r'\.(?:target|binaryTarget|systemLibrary|macro)\(\s*name:\s*"([^"]+)"', text))


def products_dir(top):
    path = Path(top) / DERIVED / "Build" / "Products" / "Debug-iphonesimulator"
    return path if path.is_dir() else None


def digest(top, module, products, scratch):
    """Rendered snapshot text for one module, or raise RuntimeError with the tool's message."""
    sdk = subprocess.run(["xcrun", "--show-sdk-path", "--sdk", "iphonesimulator"], capture_output=True, text=True, check=True).stdout.strip()
    arch = subprocess.run(["uname", "-m"], capture_output=True, text=True, check=True).stdout.strip()
    out = Path(scratch) / f"{module}.json"
    cmd = ["xcrun", "swift-api-digester", "-dump-sdk", "-module", module, "-I", str(products),
           "-sdk", sdk, "-target", f"{arch}-apple-ios17.0-simulator", "-abort-on-module-fail", "-o", str(out)]
    # C targets' generated module maps only: a Swift module's map names a Clang module of the same
    # name that would shadow it, and the per-target copies of a map redefine the module.
    for m in sorted(Path(top, DERIVED).glob("Build/Intermediates.noindex/GeneratedModuleMaps-iphonesimulator/*.modulemap")):
        if not (Path(products) / f"{m.stem}.swiftmodule").exists():
            cmd += ["-Xcc", f"-fmodule-map-file={m}"]
    run = subprocess.run(cmd, cwd=top, capture_output=True, text=True, check=False)
    # Without -abort-on-module-fail the digester exits 0 and writes an empty dump when the module
    # fails to load; the message check stays as a second guard.
    if run.returncode or not out.is_file() or "Failed to load module" in run.stderr:
        raise RuntimeError(f"{module}: " + ((run.stderr or run.stdout).strip().splitlines() or ["no output"])[-1])
    return render_dump(module, json.loads(out.read_text()), package_modules(top))


def generate(top, build=False):
    """{module: text} for every library product, or raise RuntimeError."""
    if sys.platform != "darwin" or not shutil.which("xcrun"):
        raise RuntimeError("the Swift snapshots need macOS with Xcode (swift-api-digester)")
    if build and subprocess.run(BUILD, cwd=top, check=False).returncode:
        raise RuntimeError(f"the iOS Simulator build failed: {' '.join(BUILD)}")
    products = products_dir(top)
    if not products:
        raise RuntimeError(f"no iOS Simulator build in {DERIVED}: run with --build, or `{' '.join(BUILD)}`")
    with tempfile.TemporaryDirectory() as scratch:
        return {m: digest(top, m, products, scratch) for m in swift_products(top)}


# ---------------------------------------------------------------- reading

def snapshot_files(top):
    """{name: path} of every committed snapshot: Swift modules and Kotlin Gradle modules."""
    top = Path(top)
    files = {p.stem: p for p in sorted((top / SWIFT_DIR).glob("*.txt"))}
    for p in sorted((top / "Android").glob("*/api/*.api")):
        files.setdefault(f":{p.parent.parent.name}", p)
    return files


def find_snapshot(top, name):
    files = snapshot_files(top)
    if name in files:
        return name, files[name]
    # Case-insensitive: a Swift product first, then the Gradle module (`core` is Core, `:core` the module).
    for key in (k for k in files if k.lower() == name.lower()):
        return key, files[key]
    key = f":{name.lstrip(':')}"
    return (key, files[key]) if key in files else (None, None)


def public_lines(path):
    return [ln for ln in Path(path).read_text().splitlines() if ln and not ln.startswith("#")]


# ---------------------------------------------------------------- command

def run(args, reg, root):
    pid, top = hub.platform(reg, root)
    if not top:
        print("the OpenCine platform checkout is not available", file=sys.stderr)
        return INCOMPLETE
    if args.check or args.write:
        try:
            fresh = generate(top, args.build)
        except RuntimeError as err:
            print(f"api: {err}", file=sys.stderr)
            return INCOMPLETE
        out_dir = Path(top) / SWIFT_DIR
        current = {p.stem: p.read_text() for p in out_dir.glob("*.txt")} if out_dir.is_dir() else {}
        changed = sorted(m for m in set(fresh) | set(current) if fresh.get(m) != current.get(m))
        if args.write:
            out_dir.mkdir(parents=True, exist_ok=True)
            for m in changed:
                target = out_dir / f"{m}.txt"
                target.write_text(fresh[m]) if m in fresh else target.unlink()
            print(f"api: {len(fresh)} Swift modules, {len(changed)} file(s) updated")
            return OK
        if not changed:
            print(f"api: {len(fresh)} Swift module snapshots match the build")
            return OK
        for m in changed:
            old, new = set(public_lines_text(current.get(m, ""))), set(public_lines_text(fresh.get(m, "")))
            print(f"{m}: public API changed (+{len(new - old)} -{len(old - new)})")
            for line in sorted(new - old)[:args.limit]:
                print(f"  + {line}")
            for line in sorted(old - new)[:args.limit]:
                print(f"  - {line}")
        print(f"Unrecorded public API change. If it is intended, run {UPDATE}.")
        return FAIL
    if not args.module:
        files = snapshot_files(top)
        for name, p in files.items():
            print(f"{name:34} {len(public_lines(p)):5} lines  {p.relative_to(top)}")
        if not files:
            print("no API snapshots committed yet")
        return OK
    name, path = find_snapshot(top, args.module)
    if not path:
        print(f"{args.module}: no API snapshot (atlas api lists them)", file=sys.stderr)
        return USAGE
    lines = public_lines(path)
    if args.grep:
        lines = [ln for ln in lines if args.grep.lower() in ln.lower()]
    print(f"{name}: {len(lines)} line(s) from {path.relative_to(top)}")
    print("\n".join(lines[:args.limit]))
    if len(lines) > args.limit:
        print(f"... {len(lines) - args.limit} more (--limit, --grep)")
    return OK


def public_lines_text(text):
    return [ln for ln in text.splitlines() if ln and not ln.startswith("#")]
