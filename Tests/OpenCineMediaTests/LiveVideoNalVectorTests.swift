import Foundation
import Testing

@testable import OpenCineMedia

/// Pins `LiveVideo` per-unit classification to `Fixtures/live-video-nal-vectors.tsv`, which the
/// Kotlin `LiveVideoNalVectorTest` replays. After an intended change, regenerate with
/// `OPENCINE_WRITE_FIXTURES=1 swift test --filter LiveVideoNalVectorTests` and review the diff.
@Suite struct LiveVideoNalVectorTests {
    static let fixture = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        .appending(path: "Fixtures/live-video-nal-vectors.tsv")

    @Test func fixtureMatchesSwift() throws {
        let rendered = Self.render()
        if ProcessInfo.processInfo.environment["OPENCINE_WRITE_FIXTURES"] == "1" {
            try rendered.write(to: Self.fixture, atomically: true, encoding: .utf8)
        }
        #expect(try String(contentsOf: Self.fixture, encoding: .utf8) == rendered)
    }

    static func render() -> String {
        var lines = [
            "# Generated by Tests/OpenCineMediaTests/LiveVideoNalVectorTests.swift. Do not edit by hand.",
            "# name\tinput\tparameterSetAnnexB\tnalTypeSummary\tkeyframe\tcodec ('-' = nil or empty)",
        ]
        for (name, bytes) in inputs() {
            let codec = LiveVideo.detect(annexB: bytes).map { $0 == .avc ? "avc" : "hevc" } ?? "-"
            let summary = LiveVideo.nalTypeSummary(bytes)
            lines.append(
                [
                    name, hex(bytes), hex(LiveVideo.parameterSetAnnexB(bytes) ?? []),
                    summary.isEmpty ? "-" : summary,
                    LiveVideo.accessUnitCarriesKeyframe(bytes) ? "1" : "0", codec,
                ].joined(separator: "\t"))
        }
        return lines.joined(separator: "\n") + "\n"
    }

    static func hex(_ bytes: [UInt8]) -> String {
        bytes.isEmpty ? "-" : bytes.map { String(format: "%02x", $0) }.joined()
    }

    static func inputs() -> [(String, [UInt8])] {
        let sc4: [UInt8] = [0, 0, 0, 1]
        let sc3: [UInt8] = [0, 0, 1]
        func au(_ parts: [UInt8]...) -> [UInt8] { parts.flatMap { $0 } }
        // Real Pocket live-view parameter sets (HevcTests).
        let vps = bytes("40010c01ffff21600000030000030000030000030096ac0c0000030004000003006540")
        let sps = bytes("42010121600000030000030000030000030096a00280802d17aeedc9ae5d4d404040410000030001000003001908")
        let pps = bytes("4401c17312240890")
        let metadata: [UInt8] = au([0x11, 0, 0, 1, 0x41, 0x22, 0, 0, 1, 0x40], [UInt8](repeating: 0x33, count: 15))
        let nanoSei: [UInt8] = au([6, 0xF0, 25], metadata, [0x80])
        let nanoSeiNoMarker: [UInt8] = au([6, 0xF0, 25], metadata, [0x7F])
        var out: [(String, [UInt8])] = []
        out.append(("empty", []))
        out.append(("no-start-code", [0x40, 0x01, 0x0C]))
        out.append(("only-zeros", [0, 0, 0, 0, 0]))
        out.append(("start-code-at-end", au([0x26, 0x01], sc4)))
        out.append(("hevc-pocket-irap", au(sc4, vps, sc4, sps, sc4, pps, sc4, [0x26, 0x01, 0xAF, 0x09])))
        out.append(("hevc-p-slice", au(sc4, [0x02, 0x01, 0xD0, 0x10])))
        out.append(("hevc-bla-w-lp", au(sc4, [0x20, 0x01, 0xAA])))
        out.append(("hevc-cra", au(sc3, [0x2A, 0x01, 0xAA])))
        out.append(("hevc-idr-n-lp-alone", au(sc3, [0x28, 0x01, 0xAA])))
        out.append(("hevc-sei-then-sets", au(sc4, [0x4E, 0x01, 0x05], sc4, vps, sc3, sps, sc3, pps)))
        out.append(("avc-sps-pps-idr", au(sc4, [0x67, 0x42, 0x00, 0x1F], sc4, [0x68, 0xCE, 0x3C, 0x80], sc4, [0x65, 0x88, 0x84])))
        out.append(("avc-p-slice-0x41", au(sc4, [0x41, 0x9A, 0x02])))
        out.append(("avc-aud-sei-first", au(sc4, [0x09, 0x10], sc4, [0x06, 0x05, 0x11], sc4, [0x67, 0x64], sc4, [0x68, 0xEE])))
        out.append(("trailing-zeros", au(sc4, [0x42, 0x01, 0x07, 0, 0, 0], sc3, [0x44, 0x01, 0, 0])))
        out.append(("emulation-prevention", au(sc4, [0x42, 0x01, 0x00, 0x00, 0x03, 0x01], sc4, [0x02, 0x01, 0x00, 0x00, 0x03])))
        out.append(("nano-private-sei-skipped", au(sc3, nanoSei, sc3, [0x65, 0x88])))
        out.append(("nano-sei-without-marker", au(sc3, nanoSeiNoMarker, sc3, [0x65, 0x88])))
        out.append(("hevc-before-avc", au(sc4, [0x40, 0x01], sc4, [0x67, 0x42])))
        out.append(("avc-before-hevc", au(sc4, [0x68, 0xCE], sc4, [0x44, 0x01])))
        out.append(("empty-nals-between", au(sc3, sc3, sc4, [0x42, 0x01])))
        // Seeded noise biased toward start codes and header bytes, so splitting and typing edge
        // cases show up without hand-writing each one.
        var state: UInt64 = 0x0C1E_2026_1001
        func next() -> UInt64 {
            state = state &* 6_364_136_223_846_793_005 &+ 1_442_695_040_888_963_407
            return state >> 33
        }
        let alphabet: [UInt8] = [0, 0, 0, 0, 1, 1, 3, 0x40, 0x42, 0x44, 0x67, 0x68, 0x65, 0x41, 0x26, 0x28, 0x02, 0x06, 0xF0, 25, 0x80]
        for n in 0..<40 {
            var noise: [UInt8] = []
            for _ in 0..<Int(next() % 24) {
                switch next() % 6 {
                case 0: noise += next() % 2 == 0 ? sc3 : sc4
                case 1: noise.append(UInt8(truncatingIfNeeded: next()))
                default: noise.append(alphabet[Int(next() % UInt64(alphabet.count))])
                }
            }
            out.append(("noise-\(n)", noise))
        }
        return out
    }

    static func bytes(_ hex: String) -> [UInt8] {
        stride(from: 0, to: hex.count, by: 2).map {
            let start = hex.index(hex.startIndex, offsetBy: $0)
            return UInt8(hex[start..<hex.index(start, offsetBy: 2)], radix: 16)!
        }
    }
}
